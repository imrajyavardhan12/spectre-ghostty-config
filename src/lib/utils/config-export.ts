import type { ConfigValues } from "@/lib/schema/types";
import { getConfigOption, isPathOption } from "@/lib/utils/config-options";
import {
  getOptionKeyForTarget,
  isChoiceSupportedIn,
  isKnownGhosttyRelease,
  isOptionSupportedIn,
  isThemeValueSupportedIn,
} from "@/lib/ghostty-versions";
import { normalizePaletteEntries } from "@/lib/utils/palette";
import { GHOSTTY_COMPATIBILITY_VERSION } from "@/lib/compatibility";
import { SPECTRE_VERSION } from "@/lib/version";
import { containsConfigLineBreak } from "@/lib/security/config-value-safety";

function formatValue(key: string, value: unknown): string {
  const option = getConfigOption(key);

  if (value === null || value === undefined) return "";

  // Convert UI sentinel back to Ghostty's empty-string enum default.
  if (value === "default" && option?.type === "enum") {
    return "";
  }

  if (option?.type === "boolean") {
    return value ? "true" : "false";
  }

  if (typeof value === "string") {
    if (isPathOption(key) && value.startsWith("?")) {
      return value;
    }

    if (
      isPathOption(key) &&
      value.startsWith('"?') &&
      value.endsWith('"')
    ) {
      // Ghostty's file iterator removes one outer quote pair before the path
      // parser runs. Keep an inner pair so a leading ? remains a required-path
      // character instead of becoming the optional-file marker.
      return `"${value}"`;
    }

    if (value.includes(" ")) {
      return `"${value}"`;
    }
  }

  return String(value);
}

export function exportGhosttyConfig(
  config: ConfigValues,
  appliedTheme?: string | null,
  targetVersion?: string
): string {
  const unknownOptionCount = Object.keys(config).filter(
    (key) => !getConfigOption(key)
  ).length;
  // Newer-than-target options are named explicitly so the file fails loudly
  // instead of misbehaving silently on older Ghostty releases. Nothing is
  // dropped: Ghostty ignores unknown options and the user may upgrade.
  // Unknown (unverified) options keep their existing warning instead.
  const effectiveTarget = targetVersion && isKnownGhosttyRelease(targetVersion)
    ? targetVersion
    : undefined;
  const newerOptions = effectiveTarget
    ? Object.keys(config)
      .filter((key) => getConfigOption(key) && !isOptionSupportedIn(key, effectiveTarget))
      .sort()
    : [];
  // Enum values and built-in themes added after the target release, such as
  // copy-on-select = both.
  const newerValues = effectiveTarget
    ? Object.entries(config)
      // A value with a line break is omitted from the file, and must not be echoed into a comment either.
      .filter(([, value]) => !containsConfigLineBreak(value))
      .filter(([key, value]) =>
        key === "theme"
          ? !isThemeValueSupportedIn(value, effectiveTarget)
          : typeof value === "string" && !isChoiceSupportedIn(key, value, effectiveTarget)
      )
      .map(([key, value]) => `${key} = ${value}`)
      .sort()
    : [];
  // Values with line breaks would inject extra config lines, so they are
  // omitted and counted instead of written. Share links reject them upstream;
  // this guards every other path into the store.
  const lineBreakKeys = Object.entries(config)
    .filter(([, value]) => containsConfigLineBreak(value))
    .map(([key]) => key)
    .sort();
  const lines: string[] = [
    `# Generated by Spectre v${SPECTRE_VERSION} - Ghostty Config Generator`,
    `# Spectre schema target: Ghostty ${GHOSTTY_COMPATIBILITY_VERSION}`,
  ];

  if (unknownOptionCount > 0) {
    lines.push(
      `# Warning: contains ${unknownOptionCount} ${unknownOptionCount === 1 ? "option" : "options"} outside this schema target; validate with your Ghostty build.`
    );
  }

  if (newerOptions.length > 0 && effectiveTarget) {
    lines.push(
      `# Warning: ${newerOptions.length} ${newerOptions.length === 1 ? "option requires" : "options require"} Ghostty newer than ${effectiveTarget}: ${newerOptions.join(", ")}.`
    );
  }

  if (newerValues.length > 0 && effectiveTarget) {
    lines.push(
      `# Warning: ${newerValues.length} ${newerValues.length === 1 ? "value requires" : "values require"} Ghostty newer than ${effectiveTarget}: ${newerValues.join(", ")}.`
    );
  }

  if (lineBreakKeys.length > 0) {
    lines.push(
      `# Warning: omitted ${lineBreakKeys.length} ${lineBreakKeys.length === 1 ? "option" : "options"} with line breaks in the value: ${lineBreakKeys.join(", ")}.`
    );
  }

  lines.push("# https://github.com/imrajyavardhan12/spectre-ghostty-config");

  if (appliedTheme) {
    lines.push(`# Theme: ${appliedTheme}`);
  }

  lines.push("");

  // Group options by category for organized output.
  const categories = new Map<string, string[]>();

  for (const [key, value] of Object.entries(config)) {
    if (containsConfigLineBreak(value)) continue;

    const option = getConfigOption(key);
    const category = option?.category || "other";
    // A rename leaves older releases knowing only the old key.
    const outKey = getOptionKeyForTarget(key, effectiveTarget ?? GHOSTTY_COMPATIBILITY_VERSION);

    if (!categories.has(category)) {
      categories.set(category, []);
    }

    if (Array.isArray(value)) {
      const items = key === "palette" ? normalizePaletteEntries(value as string[]) : value;
      for (const item of items) {
        categories.get(category)!.push(`${outKey} = ${formatValue(key, item)}`);
      }
    } else {
      categories.get(category)!.push(`${outKey} = ${formatValue(key, value)}`);
    }
  }

  for (const [category, configLines] of categories) {
    if (configLines.length > 0) {
      lines.push(`# ${category.charAt(0).toUpperCase() + category.slice(1)}`);
      lines.push(...configLines);
      lines.push("");
    }
  }

  return lines.join("\n");
}
