#!/usr/bin/env bun
// Generates src/data/ghostty-x11-colors.ts: the X11 color names Ghostty accepts, with their values,
// from src/terminal/res/rgb.txt at the pinned Ghostty commit.
// Pass --check to fail instead of writing when the committed table is stale.

import { readFile, writeFile } from "node:fs/promises";
import compatibility from "../compatibility.json";

const OUTPUT = new URL("../src/data/ghostty-x11-colors.ts", import.meta.url);
const ref = compatibility.ghostty.configCommit;
const SOURCE = `https://raw.githubusercontent.com/ghostty-org/ghostty/${ref}/src/terminal/res/rgb.txt`;
const HEADERS = { "User-Agent": "Mozilla/5.0 (spectre-ghostty-config x11 colors)" };

const hex = (channel: number) => channel.toString(16).padStart(2, "0");

/**
 * Reads rgb.txt the way src/terminal/x11_color.zig does: fixed columns for the three channels, the
 * name after column 12 with spaces and tabs trimmed. Ghostty compares names ignoring ASCII case, so
 * they are stored lowercased.
 */
function parseRgbTxt(text: string): [string, string][] {
  const entries: [string, string][] = [];
  const seen = new Set<string>();
  for (const raw of text.split("\n")) {
    const line = raw.endsWith("\r") ? raw.slice(0, -1) : raw;
    if (line === "") continue;
    const channels = [line.slice(0, 3), line.slice(4, 7), line.slice(8, 11)].map((part) => {
      const value = part.trim();
      if (!/^[0-9]+$/.test(value) || Number(value) > 255) throw new Error(`Bad channel in rgb.txt line: ${line}`);
      return Number(value);
    });
    const name = line
      .slice(12)
      .replace(/^[ \t]+|[ \t]+$/g, "")
      .replace(/[A-Z]/g, (c) => c.toLowerCase());
    if (!name) throw new Error(`Missing name in rgb.txt line: ${line}`);
    if (seen.has(name)) throw new Error(`Duplicate name in rgb.txt: ${name}`);
    seen.add(name);
    entries.push([name, `#${channels.map(hex).join("")}`]);
  }
  if (entries.length < 700) throw new Error(`Unexpected rgb.txt contents (${entries.length} names)`);
  return entries;
}

async function main() {
  const response = await fetch(SOURCE, { headers: HEADERS, signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`Failed to fetch ${SOURCE}: ${response.status} ${response.statusText}`);
  const entries = parseRgbTxt(await response.text());

  const output = `// Generated by scripts/generate-ghostty-x11-colors.ts. Do not edit.
// X11 color names accepted by Ghostty ${compatibility.ghostty.tag} (${ref}), from
// ${SOURCE}
// License: MIT/X11 (see Ghostty src/terminal/x11_color.zig).
// Keys are lowercased: Ghostty compares names ignoring ASCII case.

export const GHOSTTY_X11_COLORS: ReadonlyMap<string, string> = new Map([
${entries.map(([name, value]) => `  [${JSON.stringify(name)}, ${JSON.stringify(value)}],`).join("\n")}
]);
`;

  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== output) {
      console.error(
        "X11 color table is out of date with the pinned Ghostty source.\n" +
          "Run `bun run colors:x11` and review the diff."
      );
      process.exit(1);
    }
    console.log(`X11 colors match Ghostty ${compatibility.ghostty.tag} (${entries.length} names).`);
    return;
  }

  await writeFile(OUTPUT, output);
  console.log(`Wrote ${entries.length} X11 colors to ${OUTPUT.pathname}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
